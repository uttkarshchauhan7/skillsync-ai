(() => {
  'use strict';

  const MAX_FILE_BYTES = 3 * 1024 * 1024;
  const MAX_RESUME_CHARS = 18000;
  const SAMPLE_PDF = 'sample-files/sample-resume.pdf';
  const SAMPLE_JOB = 'We are looking for a Junior Frontend Developer who can build responsive web interfaces. Required skills: HTML, CSS, JavaScript, React, responsive web design, DOM manipulation, Git, GitHub and REST API integration. The candidate should understand debugging, accessibility, reusable components and teamwork. Knowledge of Python and SQL is a plus.';

  const $ = (id) => document.getElementById(id);
  const fileInput = $('resumeFile');
  const dropZone = $('dropZone');
  const fileSelected = $('fileSelected');
  const fileName = $('fileName');
  const fileSize = $('fileSize');
  const extractStatus = $('extractStatus');
  const jobDescription = $('jobDescription');
  const analyzeButton = $('analyzeButton');
  const loadingPanel = $('loadingPanel');
  const errorMessage = $('errorMessage');
  const resultsSection = $('resultsSection');
  const apiUrl = (window.APP_CONFIG && window.APP_CONFIG.API_URL || '').trim();
  const awsMode = /^https:\/\//i.test(apiUrl) && !apiUrl.includes('PASTE_YOUR');

  let selectedFile = null;
  let extractedText = '';

  $('modeLabel').textContent = awsMode ? 'AWS BACKEND CONFIGURED' : 'LOCAL DEMO MODE';
  $('modePill').classList.toggle('mode-live', awsMode);
  $('modePill').title = awsMode ? 'A Lambda URL is configured. Run a real analysis to verify AWS connectivity.' : 'Local preview mode: results are keyword-based, not generated by an AI model.';
  $('resultMode').textContent = awsMode ? 'AMAZON BEDROCK ANALYSIS' : 'LOCAL DEMO ESTIMATE';

  if (window.pdfjsLib) {
    window.pdfjsLib.GlobalWorkerOptions.workerSrc = 'https://cdnjs.cloudflare.com/ajax/libs/pdf.js/3.11.174/pdf.worker.min.js';
  }

  function showError(message) {
    errorMessage.textContent = message;
    errorMessage.hidden = false;
  }
  function clearError() {
    errorMessage.textContent = '';
    errorMessage.hidden = true;
  }
  function formatBytes(bytes) {
    return bytes < 1024 * 1024 ? `${Math.max(1, Math.round(bytes / 1024))} KB` : `${(bytes / (1024 * 1024)).toFixed(2)} MB`;
  }
  function setExtractStatus(message, state = '') {
    extractStatus.textContent = message;
    extractStatus.classList.toggle('status-success', state === 'success');
    extractStatus.classList.toggle('status-error', state === 'error');
  }
  function resetFile() {
    selectedFile = null;
    extractedText = '';
    fileInput.value = '';
    fileSelected.hidden = true;
    dropZone.hidden = false;
    setExtractStatus('PDF text is read in your browser before analysis.');
  }

  async function readPdfText(file) {
    if (!window.pdfjsLib) throw new Error('The PDF reader could not load. Check your internet connection and refresh the page.');
    const data = await file.arrayBuffer();
    const pdf = await window.pdfjsLib.getDocument({ data }).promise;
    const pages = [];
    for (let pageNo = 1; pageNo <= pdf.numPages; pageNo += 1) {
      const page = await pdf.getPage(pageNo);
      const content = await page.getTextContent();
      pages.push(content.items.map(item => item.str || '').join(' '));
    }
    return pages.join('\n').replace(/\s+/g, ' ').trim();
  }

  async function chooseFile(file) {
    clearError();
    if (!file) return;
    if (file.type !== 'application/pdf' && !file.name.toLowerCase().endsWith('.pdf')) {
      showError('Please choose a PDF file.');
      return;
    }
    if (!file.size || file.size > MAX_FILE_BYTES) {
      showError(file.size ? 'The PDF is larger than 3 MB. Please choose a smaller file.' : 'The selected file is empty.');
      return;
    }
    selectedFile = file;
    dropZone.hidden = true;
    fileSelected.hidden = false;
    fileName.textContent = file.name;
    fileSize.textContent = formatBytes(file.size);
    setExtractStatus('Reading the PDF text in your browser…');
    try {
      extractedText = await readPdfText(file);
      if (extractedText.length > MAX_RESUME_CHARS) extractedText = extractedText.slice(0, MAX_RESUME_CHARS);
      if (extractedText.length < 80) throw new Error('Very little selectable text was found. This may be a scanned PDF. Please use a text-based PDF.');
      setExtractStatus(`Text extracted successfully · ${extractedText.length.toLocaleString()} characters`, 'success');
    } catch (error) {
      resetFile();
      showError(error.message || 'Could not read this PDF. Please try another file.');
    }
  }

  fileInput.addEventListener('change', event => chooseFile(event.target.files[0]));
  $('removeFile').addEventListener('click', () => { resetFile(); clearError(); });
  $('sampleButton').addEventListener('click', async () => {
    clearError();
    try {
      const response = await fetch(SAMPLE_PDF);
      if (!response.ok) throw new Error('Could not load the sample PDF. Download it from the sample-files folder and upload it manually.');
      const blob = await response.blob();
      const file = new File([blob], 'sample-resume.pdf', { type: 'application/pdf' });
      await chooseFile(file);
    } catch (error) { showError(error.message); }
  });
  $('jobSampleButton').addEventListener('click', () => {
    jobDescription.value = SAMPLE_JOB;
    updateCharCount();
    jobDescription.focus();
  });

  function updateCharCount() { $('charCount').textContent = `${jobDescription.value.length.toLocaleString()} / 12,000`; }
  jobDescription.addEventListener('input', updateCharCount);
  ['dragenter', 'dragover'].forEach(type => dropZone.addEventListener(type, event => {
    event.preventDefault(); dropZone.classList.add('dragging');
  }));
  ['dragleave', 'drop'].forEach(type => dropZone.addEventListener(type, event => {
    event.preventDefault(); dropZone.classList.remove('dragging');
  }));
  dropZone.addEventListener('drop', event => chooseFile(event.dataTransfer.files[0]));
  dropZone.addEventListener('keydown', event => {
    if (event.key === 'Enter' || event.key === ' ') { event.preventDefault(); fileInput.click(); }
  });

  // The local preview mode is deliberately transparent: it estimates skill overlap using keywords.
  // It is useful to test the UI without AWS, but it is NOT an AI/Bedrock response.
  const SKILLS = [
    ['HTML', /\bhtml5?\b/i], ['CSS', /\bcss3?\b/i], ['JavaScript', /\bjavascript\b|\bjs\b/i],
    ['React', /\breact(?:\.js)?\b/i], ['Angular', /\bangular\b/i], ['Vue.js', /\bvue(?:\.js)?\b/i],
    ['Node.js', /\bnode(?:\.js)?\b/i], ['Express.js', /\bexpress(?:\.js)?\b/i], ['Python', /\bpython\b/i],
    ['Java', /\bjava\b/i], ['C++', /\bc\+\+\b/i], ['SQL', /\bsql\b/i], ['MySQL', /\bmysql\b/i],
    ['MongoDB', /\bmongodb\b/i], ['AWS', /\baws\b|amazon web services/i], ['Git', /\bgit\b/i],
    ['GitHub', /\bgithub\b/i], ['REST APIs', /\brest(?:ful)?\s?api(?:s)?\b/i], ['DOM manipulation', /\bdom manipulation\b|\bdocument object model\b/i],
    ['Responsive design', /\bresponsive (?:web )?design\b|\bmobile[- ]first\b/i], ['Figma', /\bfigma\b/i],
    ['Data Structures', /\bdata structures?\b|\bdsa\b/i], ['Algorithms', /\balgorithms?\b/i],
    ['Machine Learning', /\bmachine learning\b|\bml\b/i], ['Communication', /\bcommunication\b/i],
    ['Teamwork', /\bteamwork\b|\bcollaborat(?:e|ion|ive)\b/i], ['Problem solving', /\bproblem[- ]solving\b/i],
    ['Testing', /\btesting\b|\bunit tests?\b/i], ['Accessibility', /\baccessibility\b|\bwcag\b/i],
    ['Linux', /\blinux\b/i], ['Docker', /\bdocker\b/i], ['Kubernetes', /\bkubernetes\b/i]
  ];
  const normalize = value => String(value || '').toLowerCase().replace(/[^a-z0-9+#. ]/g, ' ');
  function findSkills(text) { return SKILLS.filter(([, regex]) => regex.test(text)).map(([name]) => name); }
  function createLocalAnalysis(resume, job) {
    const jobSkills = findSkills(job);
    const resumeSkills = findSkills(resume);
    const requiredSkills = jobSkills;
    const matching = requiredSkills.filter(skill => resumeSkills.includes(skill));
    const missing = requiredSkills.filter(skill => !resumeSkills.includes(skill));
    const score = requiredSkills.length ? Math.round((matching.length / requiredSkills.length) * 100) : 0;
    const hasProjects = /\b(project|developed|built|created|implemented)\b/i.test(resume);
    const hasExperience = /\b(intern|experience|employment|worked|developer)\b/i.test(resume);
    const strengths = [];
    if (matching.length) strengths.push(`The resume provides evidence of ${matching.slice(0, 4).join(', ')}.`);
    if (hasProjects) strengths.push('The resume mentions project or practical development work.');
    if (hasExperience) strengths.push('The resume includes experience-related information.');
    if (resumeSkills.length >= 5) strengths.push(`A range of ${resumeSkills.length} technical or professional skills is mentioned.`);
    if (!strengths.length) strengths.push('The resume text was extracted. Review its details manually for relevant experience and evidence.');
    const suggestions = [];
    if (missing.length) suggestions.push(`Add truthful examples demonstrating these required skills where applicable: ${missing.slice(0, 5).join(', ')}.`);
    if (!hasProjects) suggestions.push('Add a projects section with technologies used and your individual contribution.');
    suggestions.push('Use measurable outcomes and specific examples instead of generic statements.');
    if (!hasExperience) suggestions.push('Include internships, coursework, volunteering or relevant practical experience if available.');
    const verdict = score >= 75 ? 'Strong keyword overlap' : score >= 45 ? 'Moderate keyword overlap' : 'Limited keyword overlap';
    return {
      match_score: score,
      verdict,
      summary: `The local preview identified ${matching.length} matching skill(s) out of ${requiredSkills.length} skill(s) detected in the job description. This is a basic keyword comparison, not an AI assessment or a measure of candidate quality.`,
      matching_skills: matching,
      missing_skills: missing,
      strengths: strengths.slice(0, 4),
      improvement_suggestions: suggestions.slice(0, 4),
      experience_level: hasExperience ? 'Experience mentioned; level not verified' : 'Not clear'
    };
  }

  function addChips(targetId, items, type) {
    const target = $(targetId);
    target.replaceChildren();
    if (!Array.isArray(items) || !items.length) {
      const empty = document.createElement('span'); empty.className = 'empty-chip'; empty.textContent = 'No items identified'; target.appendChild(empty); return;
    }
    items.slice(0, 12).forEach(item => {
      const chip = document.createElement('span'); chip.className = `skill-chip ${type || ''}`; chip.textContent = String(item); target.appendChild(chip);
    });
  }
  function addBullets(targetId, items) {
    const target = $(targetId); target.replaceChildren();
    const safeItems = Array.isArray(items) ? items.slice(0, 5) : [];
    (safeItems.length ? safeItems : ['No items provided.']).forEach(item => {
      const li = document.createElement('li'); li.textContent = String(item); target.appendChild(li);
    });
  }
  function renderResults(data) {
    const score = Math.max(0, Math.min(100, Number(data.match_score) || 0));
    $('matchScore').textContent = score;
    $('scoreRing').style.setProperty('--score', `${score}%`);
    $('matchLabel').textContent = data.verdict || 'Skills match estimate';
    $('matchSummary').textContent = data.summary || 'The analysis is complete.';
    addChips('matchingSkills', data.matching_skills, 'matched');
    addChips('missingSkills', data.missing_skills, 'missing');
    addBullets('strengthsList', data.strengths);
    addBullets('suggestionsList', data.improvement_suggestions);
    $('resultMode').textContent = awsMode ? 'AMAZON BEDROCK ANALYSIS' : 'LOCAL KEYWORD DEMO · NOT AI';
    resultsSection.hidden = false;
    resultsSection.scrollIntoView({ behavior: 'smooth', block: 'start' });
  }

  async function callAwsBackend(file, resumeText, description) {
    const base64 = await new Promise((resolve, reject) => {
      const reader = new FileReader();
      reader.onload = () => resolve(String(reader.result).split(',')[1]);
      reader.onerror = () => reject(new Error('Could not read the selected PDF.'));
      reader.readAsDataURL(file);
    });
    const response = await fetch(apiUrl, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ fileName: file.name, fileBase64: base64, resumeText, jobDescription: description })
    });
    let payload;
    try { payload = await response.json(); } catch (_) { throw new Error('The AWS backend returned an unreadable response. Check the Lambda logs.'); }
    if (!response.ok) throw new Error(payload.error || `AWS request failed (${response.status}).`);
    if (!payload.analysis) throw new Error('The backend response did not contain an analysis.');
    return payload.analysis;
  }

  analyzeButton.addEventListener('click', async () => {
    clearError();
    const description = jobDescription.value.trim();
    if (!selectedFile || !extractedText) return showError('Upload a readable PDF resume first.');
    if (description.length < 40) return showError('Enter a job description with at least 40 characters.');
    analyzeButton.disabled = true;
    loadingPanel.hidden = false;
    $('loadingTitle').textContent = awsMode ? 'Amazon Bedrock is analyzing the resume' : 'Preparing the local demo report';
    $('loadingSubtitle').textContent = awsMode ? 'Uploading the PDF to private S3 storage and requesting an AI analysis…' : 'Comparing detected skills using a simple keyword-matching preview…';
    try {
      const analysis = awsMode
        ? await callAwsBackend(selectedFile, extractedText, description)
        : await new Promise(resolve => setTimeout(() => resolve(createLocalAnalysis(extractedText, description)), 850));
      renderResults(analysis);
    } catch (error) {
      showError(error.message || 'Analysis failed. Check your connection and configuration.');
    } finally {
      analyzeButton.disabled = false;
      loadingPanel.hidden = true;
    }
  });

  $('newAnalysisButton').addEventListener('click', () => {
    resetFile(); jobDescription.value = ''; updateCharCount(); resultsSection.hidden = true; clearError();
    $('analyzer').scrollIntoView({ behavior: 'smooth', block: 'start' });
  });
})();
